CREATE TABLE IF NOT EXISTS loan_applications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  phone TEXT NOT NULL,
  status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'reviewing', 'approved', 'declined')),
  id_photo_filename TEXT,
  id_photo_mime TEXT CHECK (id_photo_mime IN ('image/jpeg', 'image/png')),
  is_test BOOLEAN NOT NULL DEFAULT false,
  test_reference TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK ((id_photo_filename IS NULL) = (id_photo_mime IS NULL))
);

ALTER TABLE loan_applications ADD COLUMN IF NOT EXISTS is_test BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE loan_applications ADD COLUMN IF NOT EXISTS test_reference TEXT;
ALTER TABLE loan_applications DROP CONSTRAINT IF EXISTS loan_applications_phone_check;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint
    WHERE conname = 'loan_applications_phone_format_check'
      AND conrelid = 'loan_applications'::regclass
  ) THEN
    ALTER TABLE loan_applications
      ADD CONSTRAINT loan_applications_phone_format_check
      CHECK (
        (is_test AND phone ~ '^TEST-[0-9]{4}$') OR
        (NOT is_test AND phone ~ '^\+[1-9][0-9]{7,14}$')
      );
  END IF;
END $$;

CREATE INDEX IF NOT EXISTS loan_applications_created_at_idx
  ON loan_applications (created_at DESC);

CREATE UNIQUE INDEX IF NOT EXISTS loan_applications_test_reference_idx
  ON loan_applications (test_reference)
  WHERE test_reference IS NOT NULL;